#!/usr/bin/env python3
"""Generate desktop/logos.js from Simple Icons (https://simpleicons.org, CC0).

Usage: python scripts/gen-logos.py [icon-slug ...]
Downloads each brand's SVG from cdn.simpleicons.org, extracts the single path
plus its brand color, and writes a self-contained ES module that the settings
panel renders inline (no runtime network requests, no image assets).

Brand marks identify services; each mark remains the property of its owner.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

DEFAULT_ICONS = [
    # api-key catalog (dashboard/plugin_api.py _SETTINGS_KEYS)
    "googlegemini", "openai", "anthropic", "openrouter", "stripe", "twilio",
    "sendgrid",
    # connector accounts / local mcp servers
    "gmail", "googlecalendar", "googledrive", "github", "gitlab", "notion", "linear",
    "slack", "discord", "telegram", "spotify", "youtube", "whatsapp",
    "shopify", "paypal", "trello", "dropbox", "x", "cloudflare", "vercel",
    "netlify",
]

SVG_RE = re.compile(
    r'<svg[^>]*?(?:fill="(?P<fill>#[0-9A-Fa-f]{6})")?.*?'
    r'<title>(?P<title>[^<]*)</title>(?P<body>.*?)</svg>',
    re.S,
)

# Brand colors for icons served without an embedded fill (older simple-icons
# releases dropped them) — official palette values.
_FILL_OVERRIDES = {
    "openai": "#412991",
    "twilio": "#F22F46",
    "sendgrid": "#1A82E2",
    "slack": "#4A154B",
}


def fetch(slug: str) -> dict | None:
    # cdn.simpleicons.org first; some slugs are flaky or dropped from newer
    # releases, so fall back to the pinned v15 npm package on unpkg.
    urls = [
        f"https://cdn.simpleicons.org/{slug}",
        f"https://unpkg.com/simple-icons@15.0.0/icons/{slug}.svg",
    ]
    m = None
    for url in urls:
        svg = subprocess.run(["curl", "-sL", url], capture_output=True, text=True).stdout
        m = SVG_RE.search(svg)
        if m:
            break
    if not m:
        print(f"MISS {slug}")
        return None
    fill = (m["fill"] or _FILL_OVERRIDES.get(slug) or "").lower()
    return {"slug": slug, "title": m["title"], "fill": fill, "body": m["body"]}


def main() -> None:
    slugs = sys.argv[1:] or DEFAULT_ICONS
    marks = {}
    for slug in slugs:
        got = fetch(slug)
        if got:
            marks[slug] = got
    out = json.dumps(marks, indent=1, sort_keys=True)
    target = Path(__file__).resolve().parent.parent / "desktop" / "logos.js"
    target.write_text(
        "// Generated by scripts/gen-logos.py — DO NOT hand-edit path data.\n"
        "// Brand marks from Simple Icons (https://simpleicons.org, CC0); each mark\n"
        "// remains the property of its owner and is used for identification only.\n"
        f"export const LOGOS = {out}\n",
        encoding="utf-8",
    )
    print(f"wrote {target} with {len(marks)} marks")


if __name__ == "__main__":
    main()
